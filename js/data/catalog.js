export const CATALOG_BY_ID = new Map(CATALOG.map((movie) => [movie.id, movie]));

export const ALL_GENRES = Array.from(
  new Set(CATALOG.flatMap((movie) => movie.genres)),
).sort();

export const getCatalogMovie = (id) => CATALOG_BY_ID.get(id) ?? null;

/** Deterministic-ish "trending" ordering: popularity with a stable tiebreak. */
export function trendingCatalog(limit = 12) {
  return [...CATALOG]
    .sort((a, b) => (b.popularity ?? 0) - (a.popularity ?? 0) || a.title.localeCompare(b.title))
    .slice(0, limit);
}

export function catalogByGenre(genre, limit = 12) {
  return CATALOG.filter((movie) => movie.genres.includes(genre))
    .sort((a, b) => (b.imdb ?? 0) - (a.imdb ?? 0))
    .slice(0, limit);
}

/** Spread across decades so the "eras" rail has something to show. */
export function catalogByDecade(decade, limit = 12) {
  return CATALOG.filter((movie) => Math.floor(movie.year / 10) * 10 === decade)
    .sort((a, b) => (b.imdb ?? 0) - (a.imdb ?? 0))
    .slice(0, limit);
}
